"""The Planly agent: START → load_context → agent ⇄ tools → summarize → END (docs/AGENT.md)."""

import uuid
from datetime import date, datetime, timedelta
from typing import Annotated, Any, TypedDict

from langchain_core.language_models import BaseChatModel
from langchain_core.messages import AIMessage, AnyMessage, HumanMessage, SystemMessage, ToolMessage
from langgraph.graph import END, START, StateGraph
from langgraph.graph.message import add_messages
from langgraph.prebuilt import ToolNode
from sqlalchemy.ext.asyncio import AsyncSession, async_sessionmaker

from app.agent.tools import build_tools, format_task, local_now
from app.config import Settings
from app.services.tasks import TaskService, describe_day

TRIGGER_NAME = "planly"  # HumanMessage.name for messages generated by Planly, not typed by the user
HISTORY_LIMIT = 30

SYSTEM_PROMPT = """You are Planly, the user's personal planning agent. You keep their day realistic.

How you work:
- The current state of their plan is below. Trust it over earlier messages.
- Change things only through your tools. Never claim you changed something without calling a tool.
- To re-arrange a day, call replan_day; it does the time arithmetic. Use reschedule_task for single moves.
- Respect the user's preferences. When they state a lasting preference, call remember_preference.
- Never delete tasks. Prefer moving or marking skipped.
- When a [update] or [day review] message arrives, decide if the plan needs changing. If it still works, say so in one line and change nothing.
- Every change you make can be undone by the user, so act, then explain briefly.
- Reply in short, friendly sentences. Refer to tasks as #id "title". No markdown tables.
"""


class AgentState(TypedDict):
    messages: Annotated[list[AnyMessage], add_messages]
    now: str
    run_id: str
    context: str
    changes: list[dict]


# ---------- context and trigger messages (plain code, no LLM) ----------

async def render_context(svc: TaskService, now: datetime) -> str:
    today = now.date()
    tomorrow = today + timedelta(days=1)
    sections = [f"Now: {now.strftime('%A %Y-%m-%d %H:%M')}"]
    missed = await svc.list_tasks(missed_before=today)
    if missed:
        sections.append("Missed (todo, dated before today):\n" + "\n".join(map(format_task, missed[:20])))
    for label, day in (("Today", today), ("Tomorrow", tomorrow)):
        tasks = await svc.list_tasks(day, day)
        sections.append(f"{label}:\n" + ("\n".join(map(format_task, tasks)) or "(nothing planned)"))
    prefs = await svc.list_preferences()
    if prefs:
        sections.append("User preferences:\n" + "\n".join(f"- {p.text}" for p in prefs))
    recent = await svc.history(limit=10)
    if recent:
        sections.append(
            "Recent changes (newest first):\n"
            + "\n".join(f"- [{c.actor}] {c.summary}{' (undone)' if c.undone_at else ''}" for c in recent)
        )
    return "\n\n".join(sections)


def _minutes_between(a: datetime, b: datetime) -> int:
    return round((b - a).total_seconds() / 60)


def _span(minutes: int) -> str:
    hours, rest = divmod(minutes, 60)
    if not hours:
        return f"{rest} min"
    return f"{hours}h {rest}m" if rest else f"{hours}h"


async def task_event_message(svc: TaskService, change_set_ids: list[int], now: datetime) -> str:
    """Describe what the user just did, including whether a task finished early or late."""
    lines = []
    for cs in await svc.get_change_sets(change_set_ids):
        if cs.undone_at:
            continue
        line = cs.summary
        for event in await svc.events_for(cs.id):
            before, after = event.before or {}, event.after or {}
            if event.entity != "task" or after.get("status") != "done" or before.get("status") == "done":
                continue
            if not (after.get("date") and after.get("start_time") and after.get("duration_min")):
                continue
            planned_start = datetime.fromisoformat(f"{after['date']}T{after['start_time']}")
            planned_end = planned_start + timedelta(minutes=after["duration_min"])
            done_at = datetime.fromisoformat(after["completed_at"])
            if now.tzinfo is not None:
                done_at = done_at.astimezone(now.tzinfo)
            done_at = done_at.replace(tzinfo=None)
            delta = _minutes_between(done_at, planned_end)
            timing = f"{_span(delta)} early" if delta > 5 else f"{_span(-delta)} late" if delta < -5 else "on time"
            line += (
                f" at {done_at.strftime('%H:%M')} — planned {planned_start.strftime('%H:%M')}"
                f"–{planned_end.strftime('%H:%M')}, finished {timing}"
            )
        lines.append(line)
    if not lines:
        lines.append("(the change was undone)")
    return (
        "[update] " + "; ".join(lines)
        + ". Adjust the rest of today if it helps; if the plan still works, say so and change nothing."
    )


async def day_review_message(svc: TaskService, today: date) -> str:
    missed = await svc.list_tasks(missed_before=today)
    todays = await svc.list_tasks(today, today, status="todo")
    listed = "; ".join(f'#{t.id} "{t.title}" ({describe_day(t.date)})' for t in missed[:15]) or "none"
    return (
        f"[day review] {len(missed)} missed task{'s' * (len(missed) != 1)}: {listed}. "
        f"Today has {len(todays)} open task{'s' * (len(todays) != 1)}. "
        "Bring the missed tasks into a realistic plan (replan_day for today is usually right), then tell me what you did."
    )


# ---------- graph ----------

def _sendable(messages: list[AnyMessage]) -> list[AnyMessage]:
    """Recent history the model can accept: drop tool calls whose results never arrived
    (an interrupted run) and never start on a tool result."""
    answered = {m.tool_call_id for m in messages if isinstance(m, ToolMessage)}
    clean = [
        m for m in messages
        if not (isinstance(m, AIMessage) and m.tool_calls and any(c["id"] not in answered for c in m.tool_calls))
    ]
    clean = clean[-HISTORY_LIMIT:]
    while clean and not isinstance(clean[0], HumanMessage):
        clean.pop(0)
    return clean


def build_graph(
    llm: BaseChatModel,
    sessionmaker: async_sessionmaker[AsyncSession],
    settings: Settings,
    checkpointer: Any = None,
):
    tools = build_tools(sessionmaker, settings)
    model = llm.bind_tools(tools)

    async def load_context(state: AgentState) -> dict:
        async with sessionmaker() as session:
            return {"context": await render_context(TaskService(session), local_now(state))}

    async def agent(state: AgentState) -> dict:
        system = SystemMessage(f"{SYSTEM_PROMPT}\n--- Current plan ---\n{state['context']}")
        response = await model.ainvoke([system, *_sendable(state["messages"])])
        return {"messages": [response]}

    def route(state: AgentState) -> str:
        last = state["messages"][-1]
        return "tools" if isinstance(last, AIMessage) and last.tool_calls else "summarize"

    async def summarize(state: AgentState) -> dict:
        async with sessionmaker() as session:
            sets = await TaskService(session).change_sets_for_run(uuid.UUID(state["run_id"]))
        return {"changes": [{"id": c.id, "summary": c.summary, "undone": c.undone_at is not None} for c in sets]}

    graph = StateGraph(AgentState)
    graph.add_node("load_context", load_context)
    graph.add_node("agent", agent)
    graph.add_node("tools", ToolNode(tools))
    graph.add_node("summarize", summarize)
    graph.add_edge(START, "load_context")
    graph.add_edge("load_context", "agent")
    graph.add_conditional_edges("agent", route, {"tools": "tools", "summarize": "summarize"})
    graph.add_edge("tools", "agent")
    graph.add_edge("summarize", END)
    return graph.compile(checkpointer=checkpointer)


def trigger_human_message(text: str, *, generated: bool) -> HumanMessage:
    return HumanMessage(content=text, name=TRIGGER_NAME) if generated else HumanMessage(content=text)
